def test_batter_ab_spine_excludes_the_current_day():
    """Same leak, the other side of the matchup.

    Days 1-2 are strikeouts; day 3 is two home runs. If day 3 reached its own
    window the hr_rate would read 1.0 and the model would be told, before the
    game, how the game went.
    """
    c = duckdb.connect()
    c.execute("""
        create table at_bats as
        select * from (values
            (1, date '2024-04-01', 'strikeout', 'strikeout'),
            (1, date '2024-04-02', 'strikeout', 'strikeout'),
            (1, date '2024-04-03', 'hit',       'home_run'),
            (1, date '2024-04-03', 'hit',       'home_run')
        ) as t(batter_id, game_date, result, result_detail)
    """)
    c.execute(f"create table spine as {FORM_SPINE_BAT_AB_SQL}")
    row = c.execute(
        "select career_k_rate, career_hr_rate, career_hit_rate, career_n "
        "from spine where game_date = date '2024-04-03'").fetchone()
    assert row[0] == pytest.approx(1.0), f"k_rate {row[0]} sees day 3 -- LEAK"
    assert row[1] == pytest.approx(0.0), f"hr_rate {row[1]} sees day 3 -- LEAK"
    assert row[2] == pytest.approx(0.0)
    assert row[3] == 2


def test_home_run_rate_reads_result_detail_not_result():
    """`result` collapses single/double/triple/home_run into one `hit` bucket.

    A spine reading `result` would score every hit as a home run and look
    entirely plausible doing it -- the rate would just be four times too high.
    """
    c = duckdb.connect()
    c.execute("""
        create table at_bats as
        select * from (values
            (1, date '2024-04-01', 'hit', 'single'),
            (1, date '2024-04-01', 'hit', 'double'),
            (1, date '2024-04-01', 'hit', 'home_run'),
            (1, date '2024-04-01', 'out', 'field_out'),
            (1, date '2024-04-02', 'out', 'field_out')
        ) as t(batter_id, game_date, result, result_detail)
    """)
    c.execute(f"create table spine as {FORM_SPINE_BAT_AB_SQL}")
    row = c.execute(
        "select career_hit_rate, career_hr_rate from spine "
        "where game_date = date '2024-04-02'").fetchone()
    assert row[0] == pytest.approx(0.75), "three of four were hits"
    assert row[1] == pytest.approx(0.25), (
        f"hr_rate {row[1]} counts every hit as a home run")


def _contact_rows():
    """Two soft days, then one scorched pulled-fly day.

    Coordinates toward the left-field line, batting right-handed, so the day-3
    balls are pulled in the air -- the combination the rate exists to catch.
    """
    return """
        create table pitches as
        select * from (values
            (1, date '2024-04-01', 'in_play', 'R',  80.0, 'ground_ball', 125.42, 100.0),
            (1, date '2024-04-01', 'in_play', 'R',  80.0, 'ground_ball', 125.42, 100.0),
            (1, date '2024-04-02', 'in_play', 'R',  80.0, 'ground_ball', 125.42, 100.0),
            (1, date '2024-04-02', 'in_play', 'R',  80.0, 'ground_ball', 125.42, 100.0),
            (1, date '2024-04-03', 'in_play', 'R', 110.0, 'fly_ball',     60.0,  120.0),
            (1, date '2024-04-03', 'in_play', 'R', 110.0, 'fly_ball',     60.0,  120.0)
        ) as t(batter_id, game_date, result_category, bat_side,
               launch_speed, trajectory, hit_coord_x, hit_coord_y)
    """


def test_batter_contact_spine_excludes_the_current_day():
    c = duckdb.connect()
    c.execute(_contact_rows())
    c.execute(f"create table spine as {FORM_SPINE_BAT_CONTACT_SQL}")
    row = c.execute(
        "select career_hard_hit_rate, career_pull_air_rate, career_exit_velo, "
        "       career_n from spine where game_date = date '2024-04-03'"
    ).fetchone()
    assert row[0] == pytest.approx(0.0), f"hard_hit {row[0]} sees day 3 -- LEAK"
    assert row[1] == pytest.approx(0.0), f"pull_air {row[1]} sees day 3 -- LEAK"
    assert row[2] == pytest.approx(80.0), f"exit velo {row[2]} sees day 3 -- LEAK"
    assert row[3] == 4


def test_contact_spine_sees_prior_days_it_should():
    """The mirror of the leak test: a bound that excluded too much would pass
    every assertion above and measure nothing at all."""
    c = duckdb.connect()
    c.execute(_contact_rows())
    c.execute("""
        insert into pitches values
            (1, date '2024-04-04', 'in_play', 'R', 110.0, 'fly_ball', 60.0, 120.0)
    """)
    c.execute(f"create table spine as {FORM_SPINE_BAT_CONTACT_SQL}")
    row = c.execute(
        "select career_hard_hit_rate, career_pull_air_rate, career_n "
        "from spine where game_date = date '2024-04-04'").fetchone()
    # Four soft days plus the two scorched day-3 balls.
    assert row[2] == 6
    assert row[0] == pytest.approx(2 / 6)
    assert row[1] == pytest.approx(2 / 6)


def test_trailing_window_is_bounded(con):
    """d30 must not reach back further than 30 days."""
    con.execute("""
        insert into pitches values
            (1, date '2024-01-01', 0, 1.0),
            (1, date '2024-01-01', 0, 1.0)
    """)
    con.execute(f"create table spine as {FORM_SPINE_SQL}")
    row = con.execute(
        "select d30_n, career_n from spine where game_date = date '2024-04-03'"
    ).fetchone()
    assert row[0] == 4, "d30 must exclude the January rows"
    assert row[1] == 6, "career must include them"
